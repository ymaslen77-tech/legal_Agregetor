import assert from "node:assert/strict";
import {canOpenMilitaryPreview} from "./military-preview-access";
const base={NODE_ENV:"production",VERCEL_ENV:"production",MILITARY_PREVIEW:"1",MILITARY_PREVIEW_SCOPE:"military-feature-preview"};
assert.equal(canOpenMilitaryPreview(base),false,"explicit Production must be closed");
assert.equal(canOpenMilitaryPreview({...base,MILITARY_PREVIEW:"0"}),false);
assert.equal(canOpenMilitaryPreview({...base,VERCEL_ENV:"preview",MILITARY_PREVIEW:undefined}),false);
assert.equal(canOpenMilitaryPreview({...base,VERCEL_ENV:"preview",MILITARY_PREVIEW_SCOPE:undefined}),false);
assert.equal(canOpenMilitaryPreview({...base,VERCEL_ENV:"preview",MILITARY_PREVIEW_SCOPE:"production-disabled"}),false);
assert.equal(canOpenMilitaryPreview({...base,VERCEL_ENV:"preview"}),true,"Preview with both flags permitted");
assert.equal(canOpenMilitaryPreview({...base,VERCEL_ENV:undefined}),true,"Preview with system variables disabled permitted");
assert.equal(canOpenMilitaryPreview({NODE_ENV:"development",MILITARY_PREVIEW:"1"}),true);
assert.equal(canOpenMilitaryPreview({NODE_ENV:"development"}),false);
assert.equal(canOpenMilitaryPreview({...base,VERCEL_ENV:"preview",NODE_ENV:"test"}),false);
console.log("Military preview access: both branch-only flags, production denied, local opt-in PASS");
