/**
 * Safe, deterministic pre-document triage.
 * Never infer legal entitlement, produce a draft pleading or calculate deadline from unverified dates.
 */
export function getFamilyLaborGuidance(
  plan: FamilyLaborPlan, scenarioKey: string,
  answers: Record<string, string | undefined>
): FamilyLaborGuidance {
  const result = validateFamilyLaborIntake(plan, scenarioKey, answers);
  const scenario = plan.scenarios.find(item => item.key === scenarioKey);
  if (!scenario) throw new Error("Unknown scenario: " + plan.id + "/" + scenarioKey);
  const special = SPECIAL[plan.id];
  const sourceGate=getFamilyLaborScenarioReview(plan.id,scenarioKey);
  const guidance = [
    ...(special?.guidance ?? fallback),
    "Юридическая проверка выбранной ситуации: "+sourceGate.necessaryQualification.join("; ")+".",
    "Запрещённый автоматический вывод: "+sourceGate.noAutomaticConclusion
  ];
  const missing = [...result.missing];
  if (plan.id === "unpaid-leave") {
    if (answers.leaveGround === "чрезвычайная ситуация: нарушение условий жизнедеятельности и утрата имущества") {
      guidance.push("С 1 сентября 2026 года статья 128 ТК РФ предусматривает специальное основание отпуска без сохранения зарплаты до пяти календарных дней для работника, фактически проживающего в жилом помещении в зоне чрезвычайной ситуации при нарушении условий жизнедеятельности и утрате имущества. Проверьте оба обстоятельства, уровень ЧС и правительственный порядок предоставления.");
      guidance.push("Для этого основания необходимы подтверждения фактического проживания, воздействия чрезвычайной ситуации, утраты имущества и письменное заявление; по одному сообщению о ЧС право автоматически не подтверждается.");
    } else if (answers.leaveGround === "по соглашению сторон") {
      guidance.push("Обычное предоставление неоплачиваемого отпуска по соглашению сторон не означает безусловной обязанности работодателя его предоставить.");
    } else if (answers.leaveGround === "не знаю" || !answers.leaveGround) {
      guidance.push("До установления специальной категории работника или согласия работодателя нельзя утверждать, что отпуск обязателен.");
    } else {
      guidance.push("Проверьте законный предел продолжительности, подтверждение льготной категории и соответствующую редакцию статьи 128 ТК РФ до предъявления требования.");
    }
  }
  if (plan.id === "part-time-hours") {
    const ordinary = answers.mandatoryBasis === "по соглашению";
    const unsure = answers.mandatoryBasis === "не знаю" || !answers.mandatoryBasis;
    if (ordinary) {
      guidance.push("При установлении неполного рабочего времени по обычному соглашению сторон специальный пятидневный срок из части второй статьи 93 ТК РФ не применяется автоматически.");
    } else if (!unsure) {
      guidance.push("С 1 сентября 2026 года часть вторая статьи 93 ТК РФ предусматривает принятие решения работодателем не позднее пяти рабочих дней со дня письменного обращения работника, имеющего установленное законом основание. Проверьте принадлежность к льготной категории, доказательства и дату вручения обращения.");
    } else {
      guidance.push("До определения правового основания нельзя установить, действует ли специальный пятидневный срок по статье 93 ТК РФ.");
    }
  }
  if (plan.id === "alimony-order-objections" && answers.isLate === "да" && !answers.lateReason?.trim()) {
    missing.push("lateReason");
    guidance.push("Для поздних возражений необходимо указать конкретные препятствия своевременной подачи и подтвердить их документами.");
  }
  if (plan.id === "alimony-order-objections" && answers.roleInOrder === "взыскатель") {
    guidance.push("Возражения по статьям 128–129 ГПК РФ относятся к должнику. Взыскателю после отмены приказа нужно проверить исковой путь, а не подавать такие возражения от своего имени.");
  }
  if (plan.id === "alimony-order-objections" && result.dataComplete) {
    guidance.push("Даже при заполненных реквизитах проверка даты получения и причин пропуска срока требует оценки первичных документов.");
  }
  if (plan.id === "alimony-penalty" && answers.instrument === "нотариальное соглашение") {
    guidance.push("Для нотариального соглашения не применяйте автоматически ставку ответственности по судебному решению: проверьте условия соглашения и статью 115 СК РФ.");
  }
  if (plan.id === "alimony-penalty" && answers.fault !== "да") {
    guidance.push("Основания ответственности и доказательства вины не подтверждены: не переходите к числовому расчёту неустойки.");
  }
  if (plan.id === "alimony-enforcement" && answers.proceedingOpened === "нет") {
    guidance.push("Когда производство не возбуждено, сначала проверьте предъявление исполнительного документа и основания возбуждения, а не жалобу на бездействие по несуществующему производству.");
  }
  if (plan.id === "alimony-penalty" && result.dataComplete) {
    guidance.push("Неустойка здесь не рассчитывается автоматически и не выдается как готовое исковое требование.");
  }
  const documentsToCheck = special?.docs ?? ["Сведения из анкеты", "Подтверждающие документы", "Официальные решения и ответы государственных органов, если они имеются"];
  return {
    ...result,
    missing,
    dataComplete: result.dataComplete && missing.length === 0,
    scenarioTitle: scenario.title,
    guidance,
    documentsToCheck,
    verificationSources: Array.from(new Map(
      [...(special?.refs ?? []),...sourceGate.acts.map(key=>({
        name:FAMILY_LABOR_ACTS[key].title+" (нормы и актуальность требуют проверки)",
        url:FAMILY_LABOR_ACTS[key].url
      }))].map(x=>[x.url,x])
    ).values()),
    statusLabel: scenario.emergencyFirst ? "ЭКСТРЕННЫЙ ПОРЯДОК ДЕЙСТВИЙ"
      : (result.dataComplete && missing.length === 0) ? "ПРЕДВАРИТЕЛЬНЫЙ ЧЕК-ЛИСТ" : "НЕПОЛНАЯ АНКЕТА",
    draftDocument: null,
    legalOutcomeApproved: false
  };
}
