const built:CreditDebtDocumentTarget[]=CREDIT_DEBT_GROUPS.flatMap(group=>group.situations.map(situation=>{
  const key=group.id+"/"+situation.id;
  const data=TARGETS[key];
  if(!data||data[0]!==situation.targetResult)throw new Error("Credit/debt document target mismatch: "+key);
  return {groupId:group.id,situationId:situation.id,key,targetResult:situation.targetResult,
    title:situation.title,recipientHint:data[1],objective:data[2],
    legallyVerified:false,filingReady:false};
}));
if(built.length!==60||new Set(built.map(x=>x.key)).size!==60||Object.keys(TARGETS).length!==60)
  throw new Error("Invalid 60-case credit/debt target matrix");
export const CREDIT_DEBT_DOCUMENT_TARGETS:readonly CreditDebtDocumentTarget[]=built;
export function getCreditDebtDocumentTarget(groupId:string,situationId:string):CreditDebtDocumentTarget|null{
  return CREDIT_DEBT_DOCUMENT_TARGETS.find(x=>x.groupId===groupId&&x.situationId===situationId)??null;
}
